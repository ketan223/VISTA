import React, { useState, useEffect, useRef } from 'react';
import {
  ArrowLeft,
  Sparkles,
  Search,
  Globe,
  FileText,
  ShieldCheck,
  CheckCircle2,
  Clock,
  Download,
  Copy,
  Check,
  AlertCircle,
  FileDown,
  FileType,
} from 'lucide-react';
import type { ResearchResult, ResearchJobStatus } from '../types';

interface ResearchAgentWorkspaceProps {
  onBackToHub: () => void;
}

const SAMPLE_TOPICS = [
  'Agentic AI in 2025',
  'Quantum Computing Breakthroughs',
  'Solid-State Battery Progress',
  'CRISPR Gene Therapies',
];

export const ResearchAgentWorkspace: React.FC<ResearchAgentWorkspaceProps> = ({
  onBackToHub,
}) => {
  const [topic, setTopic] = useState('');
  const [activeJobId, setActiveJobId] = useState<string | null>(null);
  const [currentStep, setCurrentStep] = useState<number>(0);
  const [statusMessage, setStatusMessage] = useState<string>('');
  const [isRunning, setIsRunning] = useState<boolean>(false);
  const [result, setResult] = useState<ResearchResult | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [activeTab, setActiveTab] = useState<'report' | 'critic' | 'search' | 'scrape'>('report');
  const [copied, setCopied] = useState<boolean>(false);
  const [isExportingPDF, setIsExportingPDF] = useState<boolean>(false);
  const [isExportingDocx, setIsExportingDocx] = useState<boolean>(false);
  const [elapsed, setElapsed] = useState<number>(0);
  const timerRef = useRef<number | null>(null);

  // Timer effect while running
  useEffect(() => {
    if (isRunning) {
      setElapsed(0);
      timerRef.current = window.setInterval(() => {
        setElapsed((prev) => prev + 1);
      }, 1000);
    } else {
      if (timerRef.current) clearInterval(timerRef.current);
    }
    return () => {
      if (timerRef.current) clearInterval(timerRef.current);
    };
  }, [isRunning]);

  // Polling effect for active job status
  useEffect(() => {
    if (!activeJobId || !isRunning) return;

    const pollInterval = setInterval(async () => {
      try {
        const res = await fetch(`/api/research/status/${activeJobId}`);
        if (!res.ok) return;

        const data: ResearchJobStatus = await res.json();
        setCurrentStep(data.step);
        setStatusMessage(data.message);

        if (data.status === 'completed' && data.result) {
          setResult(data.result);
          setIsRunning(false);
          setActiveJobId(null);
          clearInterval(pollInterval);
        } else if (data.status === 'error') {
          setError(data.message || 'Pipeline failed during execution.');
          setIsRunning(false);
          setActiveJobId(null);
          clearInterval(pollInterval);
        }
      } catch (err) {
        console.error('Status poll error:', err);
      }
    }, 2000);

    return () => clearInterval(pollInterval);
  }, [activeJobId, isRunning]);

  const handleLaunch = async (selectedTopic?: string) => {
    const query = (selectedTopic || topic).trim();
    if (!query) {
      setError('Please provide a research topic to initiate the pipeline.');
      return;
    }

    setError(null);
    setResult(null);
    setIsRunning(true);
    setCurrentStep(1);
    setStatusMessage('Initiating multi-agent autonomous workflow...');

    try {
      const res = await fetch('/api/research/run', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ topic: query }),
      });

      if (!res.ok) {
        const errData = await res.json().catch(() => ({ detail: 'Failed to launch research job.' }));
        throw new Error(errData.detail || 'Failed to start research.');
      }

      const data = await res.json();
      setActiveJobId(data.job_id);
    } catch (err: any) {
      setError(err.message || 'Network error occurred while connecting to VISTA API.');
      setIsRunning(false);
    }
  };

  const handleCopyReport = () => {
    if (!result?.report) return;
    navigator.clipboard.writeText(result.report);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownloadReport = () => {
    if (!result) return;
    const blob = new Blob(
      [
        `# Research Intelligence Report: ${result.topic}\n\n` +
          `*Generated by VISTA Multi-AI Research Agent (ResearchMind)*\n` +
          `*Runtime: ${result.elapsed_seconds}s*\n\n---\n\n` +
          result.report +
          `\n\n---\n\n## 🧐 Adversarial Critic Review\n\n` +
          result.feedback,
      ],
      { type: 'text/markdown;charset=utf-8' }
    );
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `VISTA_Research_${result.topic.replace(/[^a-zA-Z0-9]/g, '_')}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  const handleDownloadPDF = async () => {
    if (!result) return;
    setIsExportingPDF(true);
    try {
      const res = await fetch('/api/research/export/pdf', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          topic: result.topic,
          report: result.report,
          feedback: result.feedback,
          elapsed_seconds: result.elapsed_seconds,
        }),
      });
      if (!res.ok) throw new Error('PDF generation failed on server.');
      const blob = await res.blob();
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `VISTA_Research_${result.topic.replace(/[^a-zA-Z0-9]/g, '_')}.pdf`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    } catch (err: any) {
      alert('Error generating PDF: ' + (err.message || 'Unknown error'));
    } finally {
      setIsExportingPDF(false);
    }
  };

  const handleDownloadDocx = async () => {
    if (!result) return;
    setIsExportingDocx(true);
    try {
      const res = await fetch('/api/research/export/docx', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          topic: result.topic,
          report: result.report,
          feedback: result.feedback,
          elapsed_seconds: result.elapsed_seconds,
        }),
      });
      if (!res.ok) throw new Error('Word document generation failed on server.');
      const blob = await res.blob();
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = `VISTA_Research_${result.topic.replace(/[^a-zA-Z0-9]/g, '_')}.docx`;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
    } catch (err: any) {
      alert('Error generating Word document: ' + (err.message || 'Unknown error'));
    } finally {
      setIsExportingDocx(false);
    }
  };

  const steps = [
    {
      num: '01',
      title: 'Search Agent',
      desc: 'Live Web Extraction',
      icon: Search,
      stage: 1,
    },
    {
      num: '02',
      title: 'Reader Agent',
      desc: 'Deep URL DOM Scraper',
      icon: Globe,
      stage: 2,
    },
    {
      num: '03',
      title: 'Writer Chain',
      desc: 'Synthesis & Fact Drafting',
      icon: FileText,
      stage: 3,
    },
    {
      num: '04',
      title: 'Critic Chain',
      desc: 'Adversarial Rigor Review',
      icon: ShieldCheck,
      stage: 4,
    },
  ];

  const parsedFeedback = result?.parsed_feedback;

  return (
    <div className="min-h-full p-6 lg:p-8 max-w-7xl mx-auto space-y-8">
      {/* Top Navigation & Status */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-white/[0.06] pb-5">
        <div className="flex items-center gap-3">
          <button
            onClick={onBackToHub}
            className="flex items-center gap-2 rounded-lg border border-white/[0.08] bg-[#12121a] px-3.5 py-1.5 text-xs font-medium text-zinc-300 hover:border-white/20 hover:text-white transition-all shadow-sm"
          >
            <ArrowLeft className="h-3.5 w-3.5" />
            VISTA Hub
          </button>
          <div className="h-4 w-[1px] bg-white/[0.1]" />
          <div className="inline-flex items-center gap-2 rounded-full border border-amber-500/30 bg-amber-500/10 px-3 py-0.5 text-xs text-amber-300">
            <span className="flex h-1.5 w-1.5 rounded-full bg-amber-400 animate-pulse" />
            Module 02 · Autonomous Research
          </div>
        </div>

        <div className="flex items-center gap-4 text-xs font-mono text-zinc-400">
          <div className="flex items-center gap-1.5">
            <span className="h-2 w-2 rounded-full bg-emerald-500" />
            <span>Tavily + DDGS Fallback</span>
          </div>
          <div className="flex items-center gap-1.5">
            <span className="h-2 w-2 rounded-full bg-violet-400" />
            <span>Mistral / Ollama Dual-LLM</span>
          </div>
        </div>
      </div>

      {/* Header Banner */}
      <div className="relative overflow-hidden rounded-2xl border border-amber-500/20 bg-gradient-to-br from-[#121016] via-[#101018] to-[#0d0d12] p-8 shadow-xl">
        <div className="absolute right-0 top-0 -mr-16 -mt-16 h-64 w-64 rounded-full bg-amber-500/5 blur-3xl pointer-events-none" />
        <div className="relative z-10 max-w-2xl space-y-3">
          <div className="inline-flex items-center gap-2 text-xs font-mono tracking-widest text-amber-400 uppercase">
            <Sparkles className="h-3.5 w-3.5" />
            ResearchMind Architecture
          </div>
          <h1 className="text-3xl font-extrabold tracking-tight text-white sm:text-4xl">
            Multi-AI <span className="text-transparent bg-clip-text bg-gradient-to-r from-amber-400 to-orange-400">Autonomous Research</span>
          </h1>
          <p className="text-sm text-zinc-400 leading-relaxed">
            Deploy four specialized autonomous agents in a collaborative research pipeline: live web discovery, in-depth URL extraction, publication synthesis, and strict adversarial peer review.
          </p>
        </div>
      </div>

      {/* Topic Query Bar & Quick Chips */}
      <div className="rounded-xl border border-white/[0.08] bg-[#111118] p-5 shadow-lg space-y-4">
        <div className="flex flex-col sm:flex-row gap-3">
          <div className="relative flex-1">
            <Search className="absolute left-3.5 top-1/2 -translate-y-1/2 h-4 w-4 text-zinc-500" />
            <input
              type="text"
              value={topic}
              onChange={(e) => setTopic(e.target.value)}
              onKeyDown={(e) => e.key === 'Enter' && !isRunning && handleLaunch()}
              placeholder="Enter any research thesis, topic, or emerging technology..."
              disabled={isRunning}
              className="w-full rounded-lg border border-white/[0.1] bg-[#161622] pl-10 pr-4 py-2.5 text-sm text-white placeholder-zinc-500 focus:border-amber-500/50 focus:outline-none focus:ring-2 focus:ring-amber-500/20 transition-all font-sans"
            />
          </div>
          <button
            onClick={() => handleLaunch()}
            disabled={isRunning || !topic.trim()}
            className="flex items-center justify-center gap-2 rounded-lg bg-gradient-to-r from-amber-500 to-orange-500 px-6 py-2.5 text-sm font-semibold text-zinc-950 hover:brightness-110 active:scale-[0.98] transition-all disabled:opacity-50 disabled:cursor-not-allowed shadow-md shadow-amber-500/20"
          >
            {isRunning ? (
              <>
                <div className="h-4 w-4 border-2 border-zinc-950 border-t-transparent rounded-full animate-spin" />
                <span>Running Pipeline ({elapsed}s)...</span>
              </>
            ) : (
              <>
                <Sparkles className="h-4 w-4" />
                <span>Launch Research</span>
              </>
            )}
          </button>
        </div>

        {/* Suggestion Chips */}
        <div className="flex flex-wrap items-center gap-2 pt-1 text-xs">
          <span className="text-zinc-500 font-mono text-[11px] uppercase tracking-wider">Trending:</span>
          {SAMPLE_TOPICS.map((item) => (
            <button
              key={item}
              onClick={() => {
                setTopic(item);
                if (!isRunning) handleLaunch(item);
              }}
              disabled={isRunning}
              className="rounded-full border border-white/[0.08] bg-[#181824] px-3 py-1 text-zinc-300 hover:border-amber-500/40 hover:text-amber-300 transition-colors disabled:opacity-50"
            >
              {item}
            </button>
          ))}
        </div>
      </div>

      {/* Error Alert */}
      {error && (
        <div className="flex items-center gap-3 rounded-xl border border-red-500/30 bg-red-500/10 p-4 text-xs text-red-300">
          <AlertCircle className="h-4 w-4 shrink-0 text-red-400" />
          <span>{error}</span>
        </div>
      )}

      {/* 4-Stage Multi-Agent Tracker Cards */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
        {steps.map((st) => {
          const Icon = st.icon;
          const isCurrent = isRunning && currentStep === st.stage;
          const isDone = (result !== null) || (currentStep > st.stage);
          const isWaiting = !isCurrent && !isDone;

          return (
            <div
              key={st.num}
              className={`relative overflow-hidden rounded-xl border p-4 transition-all duration-300 ${
                isCurrent
                  ? 'border-amber-500/50 bg-amber-500/[0.06] shadow-lg shadow-amber-500/10'
                  : isDone
                  ? 'border-emerald-500/30 bg-emerald-500/[0.03]'
                  : 'border-white/[0.06] bg-[#12121a]'
              }`}
            >
              <div className="flex items-center justify-between mb-3">
                <span className="font-mono text-[10px] tracking-wider text-amber-400/80 uppercase">
                  Stage {st.num}
                </span>
                {isCurrent && (
                  <span className="flex items-center gap-1 text-[11px] font-mono text-amber-400">
                    <span className="h-2 w-2 rounded-full bg-amber-400 animate-ping" />
                    Running
                  </span>
                )}
                {isDone && (
                  <span className="flex items-center gap-1 text-[11px] font-mono text-emerald-400">
                    <CheckCircle2 className="h-3.5 w-3.5" />
                    Complete
                  </span>
                )}
                {isWaiting && (
                  <span className="text-[11px] font-mono text-zinc-600">Pending</span>
                )}
              </div>

              <div className="flex items-center gap-2.5 mb-1">
                <div
                  className={`flex h-7 w-7 items-center justify-center rounded-lg border ${
                    isCurrent
                      ? 'border-amber-500/40 bg-amber-500/20 text-amber-300'
                      : isDone
                      ? 'border-emerald-500/40 bg-emerald-500/20 text-emerald-400'
                      : 'border-white/[0.08] bg-white/[0.03] text-zinc-500'
                  }`}
                >
                  <Icon className="h-4 w-4" />
                </div>
                <div className="font-semibold text-white text-sm">{st.title}</div>
              </div>

              <div className="text-xs text-zinc-400 pl-9">{st.desc}</div>

              {/* Top Accent Line */}
              <div
                className={`absolute top-0 left-0 right-0 h-[2px] transition-all duration-500 ${
                  isCurrent ? 'bg-amber-400' : isDone ? 'bg-emerald-400' : 'bg-transparent'
                }`}
              />
            </div>
          );
        })}
      </div>

      {/* Live Pipeline Status Banner */}
      {isRunning && (
        <div className="flex items-center justify-between rounded-xl border border-amber-500/30 bg-amber-500/10 px-5 py-3 text-xs text-amber-300">
          <div className="flex items-center gap-2.5">
            <div className="h-3.5 w-3.5 border-2 border-amber-400 border-t-transparent rounded-full animate-spin" />
            <span className="font-medium">{statusMessage || 'Processing agent loop...'}</span>
          </div>
          <div className="flex items-center gap-1.5 font-mono text-zinc-400">
            <Clock className="h-3.5 w-3.5" />
            <span>{elapsed}s elapsed</span>
          </div>
        </div>
      )}

      {/* Results View */}
      {result && (
        <div className="space-y-6 pt-2">
          {/* Critic Scorecard Banner */}
          <div className="relative overflow-hidden rounded-2xl border border-emerald-500/30 bg-gradient-to-r from-emerald-950/20 via-[#101914] to-[#12121a] p-6 shadow-xl">
            <div className="flex flex-col md:flex-row md:items-center justify-between gap-4">
              <div className="space-y-1">
                <div className="flex items-center gap-2">
                  <span className="rounded-full border border-emerald-500/40 bg-emerald-500/20 px-3 py-1 font-mono text-xs font-bold text-emerald-400">
                    CRITIC SCORE: {parsedFeedback?.score || '8/10'}
                  </span>
                  <span className="font-mono text-xs text-zinc-400">
                    Completed in {result.elapsed_seconds}s
                  </span>
                </div>
                <p className="text-sm text-zinc-300 italic pt-1">
                  "{parsedFeedback?.verdict || 'Well-structured analysis with validated references.'}"
                </p>
              </div>

              <div className="flex flex-wrap items-center gap-2 shrink-0">
                <button
                  onClick={handleCopyReport}
                  className="flex items-center gap-1.5 rounded-lg border border-white/[0.1] bg-[#1a1a24] px-3 py-1.5 text-xs font-medium text-zinc-300 hover:text-white hover:border-white/20 transition-colors shadow-sm"
                  title="Copy full markdown report to clipboard"
                >
                  {copied ? <Check className="h-3.5 w-3.5 text-emerald-400" /> : <Copy className="h-3.5 w-3.5" />}
                  <span>{copied ? 'Copied!' : 'Copy'}</span>
                </button>
                <button
                  onClick={handleDownloadReport}
                  className="flex items-center gap-1.5 rounded-lg border border-white/[0.1] bg-[#181824] px-3 py-1.5 text-xs font-medium text-zinc-300 hover:text-white hover:border-white/20 transition-colors shadow-sm"
                  title="Download raw Markdown report"
                >
                  <Download className="h-3.5 w-3.5 text-zinc-400" />
                  <span>.md</span>
                </button>
                <button
                  onClick={handleDownloadPDF}
                  disabled={isExportingPDF}
                  className="flex items-center gap-1.5 rounded-lg bg-indigo-500/20 border border-indigo-500/40 px-3 py-1.5 text-xs font-semibold text-indigo-300 hover:bg-indigo-500/30 transition-all shadow-sm disabled:opacity-50"
                  title="Generate publication-grade 3-page A4 PDF dossier"
                >
                  {isExportingPDF ? (
                    <div className="h-3.5 w-3.5 border-2 border-indigo-400 border-t-transparent rounded-full animate-spin" />
                  ) : (
                    <FileDown className="h-3.5 w-3.5 text-indigo-400" />
                  )}
                  <span>{isExportingPDF ? 'Generating...' : 'PDF (3-Page)'}</span>
                </button>
                <button
                  onClick={handleDownloadDocx}
                  disabled={isExportingDocx}
                  className="flex items-center gap-1.5 rounded-lg bg-sky-500/20 border border-sky-500/40 px-3 py-1.5 text-xs font-semibold text-sky-300 hover:bg-sky-500/30 transition-all shadow-sm disabled:opacity-50"
                  title="Download editable Microsoft Word (.docx) document"
                >
                  {isExportingDocx ? (
                    <div className="h-3.5 w-3.5 border-2 border-sky-400 border-t-transparent rounded-full animate-spin" />
                  ) : (
                    <FileType className="h-3.5 w-3.5 text-sky-400" />
                  )}
                  <span>{isExportingDocx ? 'Generating...' : 'Word (.docx)'}</span>
                </button>
              </div>
            </div>

            {/* Strengths & Improvements Breakdown */}
            {(parsedFeedback?.strengths?.length || parsedFeedback?.improvements?.length) && (
              <div className="mt-5 grid grid-cols-1 md:grid-cols-2 gap-4 border-t border-white/[0.08] pt-4 text-xs">
                {parsedFeedback.strengths && parsedFeedback.strengths.length > 0 && (
                  <div className="space-y-1.5">
                    <div className="font-mono font-semibold text-emerald-400 uppercase tracking-wider text-[11px]">
                      Verified Strengths
                    </div>
                    <ul className="space-y-1 text-zinc-300">
                      {parsedFeedback.strengths.map((str, idx) => (
                        <li key={idx} className="flex items-start gap-1.5">
                          <span className="text-emerald-400">✓</span>
                          <span>{str}</span>
                        </li>
                      ))}
                    </ul>
                  </div>
                )}

                {parsedFeedback.improvements && parsedFeedback.improvements.length > 0 && (
                  <div className="space-y-1.5">
                    <div className="font-mono font-semibold text-amber-400 uppercase tracking-wider text-[11px]">
                      Areas to Improve
                    </div>
                    <ul className="space-y-1 text-zinc-300">
                      {parsedFeedback.improvements.map((imp, idx) => (
                        <li key={idx} className="flex items-start gap-1.5">
                          <span className="text-amber-400">•</span>
                          <span>{imp}</span>
                        </li>
                      ))}
                    </ul>
                  </div>
                )}
              </div>
            )}
          </div>

          {/* Tab Navigation */}
          <div className="flex border-b border-white/[0.08] gap-6 text-sm">
            <button
              onClick={() => setActiveTab('report')}
              className={`pb-3 font-medium transition-colors border-b-2 ${
                activeTab === 'report'
                  ? 'border-amber-400 text-amber-300'
                  : 'border-transparent text-zinc-400 hover:text-zinc-200'
              }`}
            >
              📝 Publication Report
            </button>
            <button
              onClick={() => setActiveTab('critic')}
              className={`pb-3 font-medium transition-colors border-b-2 ${
                activeTab === 'critic'
                  ? 'border-emerald-400 text-emerald-300'
                  : 'border-transparent text-zinc-400 hover:text-zinc-200'
              }`}
            >
              🧐 Critic Review
            </button>
            <button
              onClick={() => setActiveTab('search')}
              className={`pb-3 font-medium transition-colors border-b-2 ${
                activeTab === 'search'
                  ? 'border-violet-400 text-violet-300'
                  : 'border-transparent text-zinc-400 hover:text-zinc-200'
              }`}
            >
              🔍 Raw Web Search
            </button>
            <button
              onClick={() => setActiveTab('scrape')}
              className={`pb-3 font-medium transition-colors border-b-2 ${
                activeTab === 'scrape'
                  ? 'border-cyan-400 text-cyan-300'
                  : 'border-transparent text-zinc-400 hover:text-zinc-200'
              }`}
            >
              📄 Scraped Content
            </button>
          </div>

          {/* Active Tab Content */}
          <div className="rounded-xl border border-white/[0.08] bg-[#111118] p-6 shadow-lg">
            {activeTab === 'report' && (
              <div className="prose prose-invert max-w-none prose-headings:text-white prose-p:text-zinc-300 prose-li:text-zinc-300 prose-a:text-amber-400 whitespace-pre-wrap leading-relaxed text-sm font-sans">
                {result.report}
              </div>
            )}

            {activeTab === 'critic' && (
              <div className="whitespace-pre-wrap text-sm text-zinc-300 font-sans leading-relaxed">
                {result.feedback}
              </div>
            )}

            {activeTab === 'search' && (
              <div className="space-y-3 font-mono text-xs text-zinc-300 whitespace-pre-wrap bg-[#0a0a0f] p-4 rounded-lg border border-white/[0.05]">
                {result.search_results || 'No search output recorded.'}
              </div>
            )}

            {activeTab === 'scrape' && (
              <div className="font-mono text-xs text-zinc-300 whitespace-pre-wrap bg-[#0a0a0f] p-4 rounded-lg border border-white/[0.05]">
                {result.scraped_content || 'No scraped DOM text recorded.'}
              </div>
            )}
          </div>
        </div>
      )}
    </div>
  );
};
